#include "frame_bridge_protocol.h"
#include "test_check.h"

int main()
{
    using namespace BZROpenShim::FrameBridge;
    SharedFrame f{};
    f.magic = kMagic;
    f.version = kVersion;
    f.byteSize = sizeof(f);
    f.producerPid = 42;
    f.width = 320;
    f.height = 180;
    f.format = 28;
    f.textureHandle = 0x1234;
    f.readyFenceHandle = 0x5678;
    f.qpcFrequency = 10000000;
    using OpenShimTest::Check;
    Check(ValidDescriptor(f, 42), "valid x86/x64 wire descriptor");
    Check(!ValidDescriptor(f, 43), "reject mismatched producer identity");
    f.version = 3;
    Check(!ValidDescriptor(f, 42), "reject V3 camera matrices without explicit convention");
    f.version = kVersion;
    f.version++;
    Check(!ValidDescriptor(f, 42), "reject unsupported ABI");
    f.version = kVersion;
    f.byteSize--;
    Check(!ValidDescriptor(f, 42), "reject truncated descriptor");
    f.byteSize = sizeof(f);
    f.width = 0;
    Check(!ValidDescriptor(f, 42), "reject empty surface");
    f.width = kMaxDimension + 1;
    Check(!ValidDescriptor(f, 42), "bound shared GPU allocation dimensions");
    f.width = 320;
    f.format = 10;
    Check(!ValidDescriptor(f, 42), "reject unsupported HDR format");
    f.format = 87;
    Check(ValidDescriptor(f, 42), "accept BGRA SDR");
    f.textureHandle = 0;
    Check(!ValidDescriptor(f, 42), "reject null resource handle");
    f.textureHandle = 0x1234;
    f.qpcFrequency = 0;
    Check(!ValidDescriptor(f, 42), "reject invalid timestamp scale");
    Check(!ValidDepthFrame(f), "disabled depth is invalid");
    f.depthTextureHandle = 0x9876;
    f.depthStatus = static_cast<std::uint32_t>(DepthStatus::Candidate);
    f.depthSourceFormat = 45;
    f.depthSourceSamples = 8;
    Check(ValidDepthFrame(f), "valid captured MSAA D24 depth candidate");
    f.depthSourceFormat = 40;
    f.depthSourceSamples = 1;
    f.depthReduction = 1;
    Check(ValidDepthFrame(f), "valid maximum D32 depth candidate");
    f.depthStatus = static_cast<std::uint32_t>(DepthStatus::Missing);
    Check(!ValidDepthFrame(f), "missing source must invalidate old depth pixels");
    f.depthStatus = static_cast<std::uint32_t>(DepthStatus::Candidate);
    f.depthResult = 0x80004005;
    Check(!ValidDepthFrame(f), "failed extraction is invalid even with candidate status");
    f.depthResult = 0;
    f.depthReduction = 2;
    Check(!ValidDepthFrame(f), "reject unknown sample reduction");
    f.depthReduction = 0;
    f.depthSourceSamples = 3;
    Check(!ValidDepthFrame(f), "reject unsupported sample count");
    f.depthSourceSamples = 4;
    f.depthSourceFormat = 55;
    Check(!ValidDepthFrame(f), "reject unsupported source depth format");
    f.depthSourceFormat = 45;
    f.depthTextureHandle = 0;
    Check(!ValidDepthFrame(f), "captured depth needs a shared texture");
    f.depthTextureHandle = 0x9876;
    f.depthCapturedOrdinal = 2;
    f.depthMatchingClears = 1;
    Check(!ValidDepthFrame(f), "reject impossible capture ordinal");
    f.depthMatchingClears = 3;
    Check(ValidDepthFrame(f), "valid pre-clear candidate metadata");
    return OpenShimTest::ExitCode();
}
