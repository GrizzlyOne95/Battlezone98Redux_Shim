// Enhanced stock-base import redirect policy tests. Pure logic: no engine,
// no game. Also checks that the generated payload files the policy names are
// checked in and carry en-* techniques on OSE programs.

#include "stock_enhanced_base_redirect.h"

#include <cstdio>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>
#include "test_check.h"

using OpenShimTest::Check;

using namespace BZROpenShim::StockEnhancedBase;

namespace
{
    RedirectInputs AllGood()
    {
        RedirectInputs in;
        in.enhancedResourcesReady = true;
        in.payloadPresent = true;
        return in;
    }

    bool Same(const char* a, const char* b)
    {
        return a && b && std::strcmp(a, b) == 0;
    }
}

void TestOnlyStockBasesRedirect()
{
    std::printf("TestOnlyStockBasesRedirect\n");
    Check(Same(PayloadForImport("BZBase.material"), "openshim_stock_bzbase.import"), "BZBase");
    Check(Same(PayloadForImport("bzbase.MATERIAL"), "openshim_stock_bzbase.import"), "case-insensitive");
    Check(Same(PayloadForImport("BZTerrainBase.material"), "openshim_stock_bzterrainbase.import"),
          "BZTerrainBase");
    Check(PayloadForImport("CR_BZBase.material") == nullptr, "CR base is CR's");
    Check(PayloadForImport("CR_BZTerrainBase.material") == nullptr, "CR terrain base is CR's");
    Check(PayloadForImport("sprites.material") == nullptr, "sprites stay stock");
    Check(PayloadForImport("BZBase.material ") == nullptr, "no trimming");
    Check(PayloadForImport("common/BZBase.material") == nullptr, "path-qualified import untouched");
    Check(PayloadForImport("") == nullptr, "empty");
}

void TestEveryGateFailsClosed()
{
    std::printf("TestEveryGateFailsClosed\n");
    Check(ShouldRedirect(AllGood()), "all gates open");

    RedirectInputs in = AllGood();
    in.disabled = true;
    Check(!ShouldRedirect(in), "kill switch");

    in = AllGood();
    in.enhancedResourcesReady = false;
    Check(!ShouldRedirect(in), "boot parse before the Enhanced group exists");

    in = AllGood();
    in.shadowedInCompilingGroup = true;
    Check(!ShouldRedirect(in), "a mod's own base wins");

    in = AllGood();
    in.payloadPresent = false;
    Check(!ShouldRedirect(in), "payload missing from the deployment");
}

void TestTerrainIsOptIn()
{
    std::printf("TestTerrainIsOptIn\n");
    const Redirect* base = RedirectForImport("BZBase.material");
    const Redirect* terrain = RedirectForImport("BZTerrainBase.material");
    Check(base && !base->optIn, "vehicle base on by default");
    Check(terrain && terrain->optIn, "terrain base needs the opt-in");

    RedirectInputs in = AllGood();
    in.optInRequired = true;
    Check(!ShouldRedirect(in), "terrain stays stock without the opt-in");
    in.optedIn = true;
    Check(ShouldRedirect(in), "terrain redirects when opted in");
    in.disabled = true;
    Check(!ShouldRedirect(in), "kill switch beats the opt-in");
}

void TestPayloadsAreCheckedIn()
{
    std::printf("TestPayloadsAreCheckedIn\n");
    for (const Redirect& r : kRedirects)
    {
        const std::string path = std::string(OPENSHIM_ENHANCED_PAYLOAD_DIR "/") + r.payloadFile;
        std::ifstream file(path, std::ios::binary);
        Check(static_cast<bool>(file), "payload file exists");
        if (!file)
        {
            std::printf("  missing %s\n", path.c_str());
            continue;
        }
        std::stringstream buffer;
        buffer << file.rdbuf();
        const std::string text = buffer.str();
        Check(text.find("GENERATED by scripts/generate_stock_enhanced_base.py") != std::string::npos,
              "generated header");
        Check(text.find("scheme en-high-pssm") != std::string::npos, "carries en-high-pssm");
        Check(text.find("PassSchemeENHighPSSMV2") != std::string::npos, "carries the PSSM v2 pass");
        Check(text.find("CR_BaseIBL") == std::string::npos &&
                  text.find("CR_TerrainIBL") == std::string::npos &&
                  text.find("CR_Textured") == std::string::npos,
              "no CR program survives");
    }
}

int main()
{
    TestOnlyStockBasesRedirect();
    TestEveryGateFailsClosed();
    TestTerrainIsOptIn();
    TestPayloadsAreCheckedIn();

    if (OpenShimTest::FailureCount() != 0)
    {
        std::printf("\nstock_enhanced_base_redirect_tests FAILED (%d)\n", OpenShimTest::FailureCount());
        return 1;
    }
    std::printf("\nstock_enhanced_base_redirect_tests passed\n");
    return 0;
}
